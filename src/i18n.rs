static ZH_CN_TABLE: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
static ZH_TW_TABLE: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();

fn zh_cn_table() -> &'static HashMap<&'static str, &'static str> {
    ZH_CN_TABLE.get_or_init(|| ZH_CN.iter().copied().collect())
}

fn zh_tw_table() -> &'static HashMap<&'static str, &'static str> {
    ZH_TW_TABLE.get_or_init(|| ZH_TW.iter().copied().collect())
}

/// tr(): English source string -> translation for the active language.
/// Returns the key itself when no translation exists (English fallback).
/// zh_TW falls back to the zh_CN entry when a key is missing there.
pub fn tr(lang: &str, key: &str) -> String {
    if lang == "zh_TW" {
        if let Some(v) = zh_tw_table().get(key) {
            return v.to_string();
        }
        if let Some(v) = zh_cn_table().get(key) {
            return v.to_string();
        }
    } else if lang == "zh_CN" {
        if let Some(v) = zh_cn_table().get(key) {
            return v.to_string();
        }
    }
    key.to_string()
}

/// static variant (leaks the translation once)
#[allow(dead_code)]
pub fn tr_static(lang: &str, key: &str) -> &'static str {
    if lang == "zh_TW" {
        if let Some(v) = zh_tw_table().get(key) {
            return v;
        }
        if let Some(v) = zh_cn_table().get(key) {
            return v;
        }
    } else if lang == "zh_CN" {
        if let Some(v) = zh_cn_table().get(key) {
            return v;
        }
    }
    Box::leak(key.to_string().into_boxed_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// the Language menu offers exactly these three
    #[test]
    fn offers_three_languages() {
        assert_eq!(LANGUAGES.len(), 3);
        assert_eq!(LANGUAGES[0], ("zh_CN", "简体中文"));
        assert_eq!(LANGUAGES[1], ("zh_TW", "繁體中文"));
        assert_eq!(LANGUAGES[2], ("en_US", "English"));
    }

    /// Every key the GUI looks up at run time — i.e. the ones that come from
    /// arrays or the option template instead of a `tr("literal")` call site —
    /// must have an entry in both translated tables. Bare `tr("<literal>")`
    /// keys are covered by the tables being keyed on the English source itself.
    #[test]
    fn dynamic_keys_are_translated() {
        let mut keys: Vec<String> = Vec::new();
        keys.extend(crate::app::COLUMN_TITLES.iter().map(|s| s.to_string()));
        keys.extend(
            crate::core::options::LEVEL_NAMES
                .iter()
                .map(|s| s.to_string()),
        );
        keys.extend(crate::core::dat::DOCK_NAMES.iter().map(|s| s.to_string()));
        keys.extend(
            crate::core::folders::root_folder_names(false)
                .iter()
                .map(|(_, label)| label.to_string()),
        );
        keys.extend(
            crate::core::options::GUI_CATEGORIES
                .iter()
                .map(|s| s.to_string()),
        );
        keys.extend(
            crate::core::options::CORE_CATEGORIES
                .iter()
                .map(|s| s.to_string()),
        );
        // status bar badge tooltips (ui.rs draw_status)
        keys.extend(
            [
                "status",
                "emulation",
                "color",
                "sound",
                "graphic",
                "cocktail",
                "protection",
                "savestate",
            ]
            .iter()
            .map(|s| s.to_string()),
        );
        // ROMs column
        keys.push("Yes".into());
        keys.push("No".into());
        // every long_name() token the folder tree can show
        for tok in [
            "joy2way",
            "joy4way",
            "joy8way",
            "paddle",
            "doublejoy2way",
            "doublejoy4way",
            "doublejoy8way",
            "dial",
            "lightgun",
            "pedal",
            "stick",
            "trackball",
            "vjoy2way",
            "vdoublejoy2way",
            "baddump",
            "nodump",
            "raster",
            "vector",
            "lcd",
            "card",
            "cfcard",
            "disk",
            "laserdisc",
            "vhs",
        ] {
            keys.push(crate::core::folders::long_name(tok).to_string());
        }
        keys.sort();
        keys.dedup();
        for key in &keys {
            assert!(
                zh_cn_table().contains_key(key.as_str()),
                "missing zh_CN translation for {key:?}"
            );
            assert!(
                zh_tw_table().contains_key(key.as_str()),
                "missing zh_TW translation for {key:?}"
            );
        }
        assert!(keys.len() > 60, "expected a decent-size key set");
    }

    /// The menu labels the user pinned by name, in both tables.
    ///
    /// `dynamic_keys_are_translated` only proves a key *exists*; it cannot catch a
    /// value drifting back to an older wording. That is exactly what happened to
    /// the View menu: `Font` was changed to 图标字体 in the Traditional table and
    /// the Simplified one silently kept 字体, so the two languages disagreed and
    /// the rename never took effect. Assertions live here rather than in the
    /// source so a future edit has to argue with them.
    #[test]
    fn pinned_menu_labels_are_consistent() {
        // (key, simplified, traditional)
        let pinned = [
            ("Font", "图标字体", "圖標字型"),
            ("Window Background", "窗口背景", "窗口背景"),
        ];
        for (key, zh_cn, zh_tw) in pinned {
            // the tables are `HashMap<&str, String>`, so `get` hands back `&&str`
            assert_eq!(
                zh_cn_table().get(key).copied(),
                Some(zh_cn),
                "zh_CN value for {key:?} drifted"
            );
            assert_eq!(
                zh_tw_table().get(key).copied(),
                Some(zh_tw),
                "zh_TW value for {key:?} drifted"
            );
        }
    }

    /// The rename to 图标字体 was requested because the submenu scales the whole
    /// interface, not just glyphs — but the i18n *key* stayed `"Font"`, so this
    /// test also pins the fact that the menu still looks its label up under that
    /// key. Renaming the key alone would make the menu fall back to English.
    #[test]
    fn font_menu_label_is_looked_up_by_its_original_key() {
        assert!(zh_cn_table().contains_key("Font"));
        assert!(zh_tw_table().contains_key("Font"));
        // and the old wording must be gone from the View menu's own key
        assert_ne!(zh_cn_table().get("Font").copied(), Some("字体"));
    }
}
